"""Step 5 (plain Python). Builds the report assets from the model outputs, so no number is hand-copied:
  out/scale_table.md         markdown table for RESULTS_SCALE.md
  out/scale_fig_snippet.tex  compact one-column pgfplots figure (ACM sigconf, paper palette), inline coordinates
  out/fig_test/scale_fig_test.tex  standalone acmart wrapper used only to test-compile the snippet
"""
import json
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import OUT, atomic_write_text

N_TABLE = [12, 25, 50, 100, 250, 500]
LABEL = {
    "R_random_service": "R  random ranking of N services, C(N-2,k-2)/C(N,k)",
    "R_random_entry_m5": "R' random ranking of 5N entries (paper's entry convention)",
    "i_relative_rank": "(i) relative rank, literal r -> r*N/N0",
    "i2_relative_rank_noncause": "(i') relative rank among non-causes (share above each cause kept) [95% CI]",
    "ii_noise_quiet": "(ii) noise floor, quiet pool 9+9 [95% CI]",
    "ii_noise_quiet12": "(ii) noise floor, quiet pool 12+6 (sensitivity)",
    "ii_noise_perturbed": "(ii) noise floor, perturbed pool (pessimistic)",
    "ii_noise_quiet_nocoupling_envelope": "(ii*) quiet pool with coupling removed (optimistic envelope)",
}


def f(v):
    if v == 0:
        return "0"
    if v < 0.0005:
        return "<0.001"
    return f"{v:.3f}"


def table_md(tab, summ):
    out = []
    for k in (2, 5):
        meas = summ["measured_at_N0"][str(k)]["overall"]
        out.append(f"\n**Both@{k}**: measured at N0 (5 Boutique / 3 Sock Shop candidate services): "
                   f"**{meas[0]:.3f}** [95% CI {meas[1]:.3f}, {meas[2]:.3f}]\n")
        out.append("| model | " + " | ".join(f"N={N}" for N in N_TABLE) + " |")
        out.append("|---|" + "---|" * len(N_TABLE))
        for _, r in tab[tab.k == k].iterrows():
            cells = []
            for N in N_TABLE:
                c = f(r[f"N{N}"])
                if r.model in ("ii_noise_quiet", "i2_relative_rank_noncause"):
                    c += f" [{f(r[f'N{N}_lo'])}, {f(r[f'N{N}_hi'])}]"
                cells.append(c)
            out.append(f"| {LABEL[r.model]} | " + " | ".join(cells) + " |")
    return "\n".join(out) + "\n"


def coords(df, col, nmin=None):
    d = df if nmin is None else df[df.N >= nmin]
    return " ".join(f"({int(n)},{v:.4f})" for n, v in zip(d.N, d[col]))


