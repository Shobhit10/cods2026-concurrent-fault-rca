def main():
    tab = pd.read_csv(os.path.join(OUT, "scale_table.csv"))
    pl = pd.read_csv(os.path.join(OUT, "scale_plot_data.csv"))
    with open(os.path.join(OUT, "scale_model_summary.json")) as fh:
        summ = json.load(fh)
    atomic_write_text(os.path.join(OUT, "scale_table.md"), table_md(tab, summ))
    atomic_write_text(os.path.join(OUT, "scale_fig_snippet.tex"), snippet(pl, summ))
    atomic_write_text(os.path.join(OUT, "fig_test", "scale_fig_test.tex"), test_wrapper())
    print(open(os.path.join(OUT, "scale_table.md")).read())


if __name__ == "__main__":
    main()
